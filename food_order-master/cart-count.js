// =============================================
// فایل cart-count.js
// وظیفه: نمایش تعداد کل آیتم‌های موجود در سبد خرید
// این فایل می‌تواند در چند صفحه استفاده شود تا شمارنده سبد همیشه به‌روز باشد.
// =============================================

// یک تابع می‌سازیم تا هر زمان لازم بود شمارنده سبد را دوباره محاسبه کنیم.
function updateCartCount() {

    // عنصر HTML مربوط به شمارنده سبد را با id="cart-count" پیدا می‌کنیم.
    const cartCount =
        document.querySelector("#cart-count");

    // اگر در صفحه فعلی شمارنده وجود نداشت، تابع را متوقف می‌کنیم.
    // این کار باعث می‌شود فایل بدون خطا در صفحه‌هایی که شمارنده ندارند هم اجرا شود.
    if (!cartCount) {
        return;
    }

    // سبد خرید را از localStorage می‌خوانیم.
    // چون localStorage فقط متن ذخیره می‌کند، با JSON.parse آن را دوباره به آرایه تبدیل می‌کنیم.
    // اگر هنوز سبدی ذخیره نشده باشد، یک آرایه خالی در نظر می‌گیریم.
    const cart =
        JSON.parse(localStorage.getItem("cart")) || [];

    // متغیری برای نگهداری مجموع تعداد همه آیتم‌های سبد می‌سازیم.
    let totalItems = 0;

    // روی تمام غذاهای داخل سبد حرکت می‌کنیم.
    cart.forEach(function(food) {

       // تعداد هر غذا را به مجموع تعداد آیتم‌های سبد اضافه می‌کنیم.
       totalItems += Number(food.count) || 0;
    });

    // مقدار نهایی را داخل شمارنده صفحه نمایش می‌دهیم.
    cartCount.textContent = totalItems;
}

// هنگام باز شدن صفحه، یک بار تابع را اجرا می‌کنیم تا شمارنده مقدار صحیح داشته باشد.
updateCartCount();

// در script.js بعد از تغییر سبد، یک رویداد سفارشی به نام cartUpdated ارسال می‌شود.
// اینجا به آن رویداد گوش می‌دهیم تا شمارنده بدون رفرش صفحه به‌روز شود.
document.addEventListener("cartUpdated", function() {

    // دوباره تعداد آیتم‌های سبد را محاسبه و نمایش می‌دهیم.
    updateCartCount();
});
