// فایل profile.js
// وظیفه: اعتبارسنجی فرم پروفایل قبل از ثبت اطلاعات
// =============================================

// فرم پروفایل را از صفحه پیدا می‌کنیم.
const profileForm =
    document.querySelector("#profile-form");

// به رویداد submit فرم گوش می‌دهیم؛ یعنی زمانی که کاربر فرم را ارسال می‌کند.
profileForm.addEventListener("submit", function(event) {

    // رفتار پیش‌فرض فرم را متوقف می‌کنیم تا صفحه رفرش نشود.
    event.preventDefault();

    // مقدار نام و نام خانوادگی را می‌گیریم و فاصله‌های ابتدا و انتهای آن را حذف می‌کنیم.
    const fullName =
        document.querySelector("#full-name").value.trim();

    // مقدار شماره تلفن را دریافت می‌کنیم.
    const phone =
        document.querySelector("#phone").value.trim();

    // مقدار ایمیل را دریافت می‌کنیم.
    const email =
        document.querySelector("#email").value.trim();

    // مقدار واحد سازمانی را دریافت می‌کنیم.
    const department =
        document.querySelector("#department").value.trim();

    // اگر نام کمتر از ۳ کاراکتر باشد، آن را نامعتبر در نظر می‌گیریم.
    if (fullName.length < 3) {
        alert("لطفاً نام و نام خانوادگی را به‌درستی وارد کنید.");
        return;
    }

    // الگوی شماره موبایل ایران:
    // ^09 یعنی شماره باید با 09 شروع شود.
    // \d{9} یعنی بعد از آن دقیقاً ۹ رقم قرار بگیرد.
    // در نتیجه کل شماره باید ۱۱ رقم باشد.
    const phonePattern = /^09\d{9}$/;

    // متد test بررسی می‌کند که مقدار phone با الگوی بالا مطابقت دارد یا نه.
    if (!phonePattern.test(phone)) {
        alert("لطفاً یک شماره تلفن معتبر وارد کنید.");
        return;
    }

    // یک Regular Expression ساده برای بررسی ساختار کلی ایمیل تعریف می‌کنیم.
    // ایمیل باید قبل و بعد از @ مقدار داشته باشد و بعد از آن نیز پسوند دامنه وجود داشته باشد.
    const emailPattern =
        /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

    // اگر ایمیل با الگو مطابقت نداشت، ثبت فرم متوقف می‌شود.
    if (!emailPattern.test(email)) {
        alert("لطفاً یک ایمیل معتبر وارد کنید.");
        return;
    }

    // اگر واحد سازمانی خالی باشد، اجازه ثبت نمی‌دهیم.
    if (department.length === 0) {
        alert("لطفاً واحد خود را وارد کنید.");
        return;
    }

    // اگر برنامه به این قسمت برسد، یعنی همه اعتبارسنجی‌ها موفق بوده‌اند.
    alert("اطلاعات پروفایل با موفقیت ثبت شد.");
});

// این پیام فقط برای تست اتصال صحیح فایل JavaScript به صفحه است.
console.log("profile.js وصل شد");
